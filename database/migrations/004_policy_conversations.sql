-- 기존 DB에 정책 대화 테이블이 없을 때 실행합니다.
-- 이미 안내받은 chat_conversations/chat_messages를 생성했다면 추가 실행은 필요 없습니다.
-- Supabase SQL Editor용입니다. 이미지 버킷과 기존 사용자/가게 정보는 수정하지 않습니다.
BEGIN;
-- 정책 대화: 계정당 최근 5개 보관은 PolicyConversationService가 트랜잭션으로 관리합니다.
CREATE TABLE IF NOT EXISTS chat_conversations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 store_id BIGINT NOT NULL REFERENCES stores(id),
 assistant VARCHAR(20) NOT NULL DEFAULT 'policy' CHECK (assistant IN ('policy','marketing','customer','sales')),
 title VARCHAR(200) NOT NULL DEFAULT '새 대화',
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_chat_conversations_user_updated ON chat_conversations(user_id,updated_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS idx_chat_conversations_store ON chat_conversations(store_id);
CREATE TABLE IF NOT EXISTS chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
 client_message_id UUID NOT NULL DEFAULT gen_random_uuid(),
 role VARCHAR(20) NOT NULL CHECK (role IN ('user','assistant')),
 content TEXT NOT NULL DEFAULT '',
 sources JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(sources) = 'array'),
 status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','streaming','complete','error','stopped')),
 error_code VARCHAR(100),
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uk_chat_messages_client_id UNIQUE(conversation_id,client_message_id)
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_conversation_id ON chat_messages(conversation_id,id);
ALTER TABLE public.chat_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.chat_conversations, public.chat_messages FROM anon, authenticated;
COMMIT;
