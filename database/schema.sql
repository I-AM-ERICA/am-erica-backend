-- AM-ERICA PostgreSQL 스키마 (prod 프로필은 이 스키마를 전제로 하며 테이블을 자동 생성하지 않습니다)
-- 엔티티와의 일치 여부는 SchemaValidationTest가 검증합니다.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) UNIQUE,
    password_hash VARCHAR(100),
    naver_id      VARCHAR(255) UNIQUE,
    name          VARCHAR(50)  NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE stores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT       NOT NULL REFERENCES users (id),
    name       VARCHAR(100) NOT NULL,
    category   VARCHAR(50)  NOT NULL,
    region     VARCHAR(50)  NOT NULL,
    address    VARCHAR(255),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_stores_owner ON stores (owner_id);

CREATE TABLE sales (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT  NOT NULL REFERENCES stores (id),
    sale_date   DATE    NOT NULL,
    amount      BIGINT  NOT NULL CHECK (amount >= 0),
    order_count INTEGER NOT NULL CHECK (order_count >= 0),
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_sales_store_date UNIQUE (store_id, sale_date)
);

CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   BIGINT        NOT NULL REFERENCES stores (id),
    platform   VARCHAR(30),
    rating     INTEGER       NOT NULL CHECK (rating BETWEEN 1 AND 5),
    content    VARCHAR(2000) NOT NULL,
    reply      VARCHAR(2000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_reviews_store_created ON reviews (store_id, created_at DESC);

CREATE TABLE policies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200)  NOT NULL,
    agency     VARCHAR(100)  NOT NULL,
    region     VARCHAR(50)   NOT NULL,
    category   VARCHAR(50)   NOT NULL,
    summary    VARCHAR(2000) NOT NULL,
    url        VARCHAR(500),
    apply_start DATE,
    apply_end  DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE ai_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    store_id   BIGINT      NOT NULL REFERENCES stores (id),
    assistant  VARCHAR(20) NOT NULL,
    operation  VARCHAR(50) NOT NULL,
    success    BOOLEAN     NOT NULL,
    error_code VARCHAR(50),
    latency_ms BIGINT      NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ai_logs_store ON ai_logs (store_id, id DESC);

CREATE TABLE policy_reminders (
    user_id BIGINT PRIMARY KEY REFERENCES users (id),
    store_id BIGINT REFERENCES stores (id),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    last_sent_date DATE
);
CREATE INDEX idx_policy_reminders_enabled ON policy_reminders (enabled, user_id);

CREATE TABLE account_settings (
    user_id BIGINT PRIMARY KEY REFERENCES users (id),
    store_id BIGINT REFERENCES stores (id),
    owner_name VARCHAR(50),
    policy_gender VARCHAR(4) NOT NULL DEFAULT 'boy' CHECK (policy_gender IN ('boy', 'girl')),
    marketing_gender VARCHAR(4) NOT NULL DEFAULT 'girl' CHECK (marketing_gender IN ('boy', 'girl')),
    customer_gender VARCHAR(4) NOT NULL DEFAULT 'girl' CHECK (customer_gender IN ('boy', 'girl')),
    sales_gender VARCHAR(4) NOT NULL DEFAULT 'boy' CHECK (sales_gender IN ('boy', 'girl'))
);

-- 정책 대화: 계정당 최근 5개 보관은 PolicyConversationService가 트랜잭션으로 관리합니다.
CREATE TABLE chat_conversations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 store_id BIGINT NOT NULL REFERENCES stores(id),
 assistant VARCHAR(20) NOT NULL DEFAULT 'policy' CHECK (assistant IN ('policy','marketing','customer','sales')),
 title VARCHAR(200) NOT NULL DEFAULT '새 대화',
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_chat_conversations_user_updated ON chat_conversations(user_id,updated_at DESC,id DESC);
CREATE INDEX idx_chat_conversations_store ON chat_conversations(store_id);
CREATE TABLE chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
 client_message_id UUID NOT NULL DEFAULT gen_random_uuid(),
 role VARCHAR(20) NOT NULL CHECK (role IN ('user','assistant')),
 content TEXT NOT NULL DEFAULT '',
 sources JSONB NOT NULL DEFAULT '[]',
 status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','streaming','complete','error','stopped')),
 error_code VARCHAR(100),
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uk_chat_messages_client_id UNIQUE(conversation_id,client_message_id)
);
CREATE INDEX idx_chat_messages_conversation_id ON chat_messages(conversation_id,id);
